#!/usr/bin/env node
// Writes src/units/all.js: one import per unit file, in catalogue order. Run after adding a
// unit (`pnpm --filter @trailbuddies/content units:index`); `validate` fails if it's stale.
import { readFileSync, writeFileSync, existsSync } from "node:fs";
import { join, dirname } from "node:path";
import { fileURLToPath } from "node:url";

const root = join(dirname(fileURLToPath(import.meta.url)), "..", "src");
const cat = JSON.parse(readFileSync(join(root, "catalogue.json"), "utf8"));
const camel = (id) => id.replace(/-([a-z0-9])/g, (_, c) => c.toUpperCase()).replace(/^(\d)/, "u$1");

/** The text all.js should have. */
export function unitsIndex() {
  const rows = cat.subjects.flatMap((s) =>
    s.units
      .filter((u) => existsSync(join(root, "units", s.id, `${u.id}.json`)))
      .map((u) => ({ id: u.id, name: camel(u.id), path: `./${s.id}/${u.id}` })),
  );
  return [
    "// Every unit with content, in catalogue order. Generated by `node scripts/units-index.js`;",
    "// the validator fails if a unit file is missing from this list.",
    ...rows.map((r) => `import ${r.name} from "${r.path}.json" with { type: "json" };`),
    ...rows.map((r) => `import ${r.name}Assets from "${r.path}.assets.json" with { type: "json" };`),
    "",
    "/** @type {any[]} */",
    `export const ALL_UNITS = [${rows.map((r) => r.name).join(", ")}];`,
    "",
    "/** Each unit's asset manifest (images and recordings with their review status), by unit id. */",
    "/** @type {Record<string, any>} */",
    "export const ALL_ASSETS = {",
    ...rows.map((r) => `  ${JSON.stringify(r.id)}: ${r.name}Assets,`),
    "};",
    "",
  ].join("\n");
}

if (process.argv[1] === fileURLToPath(import.meta.url)) {
  writeFileSync(join(root, "units", "all.js"), unitsIndex());
  console.log("✓ src/units/all.js updated");
}
